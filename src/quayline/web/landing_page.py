"""Issue 80: the public front page, generated from the fixture.

A stranger lands here knowing nothing. They do not know what demurrage is, they have
never heard of 46 CFR Part 541, and "recompute the days" is not a sentence yet. So the
page spends its first two sentences on the problem and nothing on the product.

The proof is the same day grid the intake leads with, produced by the same call, so
this page cannot show a number the engine disagrees with. ``web/`` is generated by
``make landing`` and never hand-written, which means a landing page whose figures were
typed into a template is not a thing that can happen here. That is the whole reason the
page is generated rather than authored.

On the honesty section at the bottom
-----------------------------------

It lists what does not exist yet, including that there is no hosted version and no
customer has used this. A landing page that only says what is good about itself is
indistinguishable from a landing page that is making things up, and this project has
nothing to trade its credibility for. The list is short because the project is early,
and it would grow honestly as the project grows.
"""

