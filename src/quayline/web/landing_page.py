def _facts(pairs: list[tuple[str, str]]) -> str:
    rows = "".join(
        f'<div><dt class="stencil">{esc(k)}</dt><dd class="data">{esc(v)}</dd></div>'
        for k, v in pairs
    )
    return f'<dl class="facts">{rows}</dl>'


def _items(entries: list[str]) -> str:
    return '<ul class="plain">' + "".join(f"<li>{esc(e)}</li>" for e in entries) + "</ul>"


def landing_page() -> str:
    """The public front page, with the proof computed rather than typed."""
    strip, result, rail_pairs = example_audit()
    allowance = dict(rail_pairs)["free time"]
    body = (
        '<div class="wrap">\n'
        '<div class="bar">'
        '<span class="stencil">Quayline</span>'
        '<span class="stencil">46 CFR Part 541</span>'
        "</div>\n"
        "<h1>A container sits. The clock runs. Somebody pays.</h1>\n"
        '<div class="prose">\n'
        "<p>When your box is sitting at a port or a rail yard longer than it should be, "
        "the terminal charges you for the delay. That bill is demurrage when the box is "
        "still there, and detention when it has left and is not returned. Both are "
        "charged per day, and both arrive as one number on one invoice.</p>\n"
        "<p>The carrier is required to publish the rule they are charging you by: the "
        "free days, the rate, and the dates they say they counted. Almost nobody checks "
        "the bill against that rule. When they do, the arithmetic is often wrong, "
        "usually by a day or two and usually in the carrier's favour.</p>\n"
        "</div>\n"
        '<div class="proof">\n'
        "<h2>The worked example, day by day</h2>\n"
        f"{rail(rail_pairs)}\n"
        f"{day_cells(strip.days)}\n"
        f"{legend()}\n"
        f"{ledger(money(result.demanded_total), money(result.recomputed_total), money(result.variance))}\n"
        "</div>\n"
        "<h2>Why the ninth day is the argument</h2>\n"
        '<div class="prose">\n'
        f"<p>The rule the carrier published allows {esc(allowance)} of free time, and "
        f"it says that free time ended on {esc(day(strip.declared_free_time_end))}. "
        f"Counting the days it discloses itself puts the end at "
        f"{esc(day(strip.recomputed_free_time_end))}. The carrier billed through the "
        f"day after that, and charged for the day in between.</p>\n"
        "<p>That is the whole dispute. Not a rounding argument and not a complaint "
        "about the rate: the carrier counted one day more than its own rule allows. "
        "The recomputation is reproducible from the invoice, which is what makes it "
        "worth sending.</p>\n"
        "</div>\n"
        "<h2>What this does today</h2>\n"
        f"{_items(EXISTS)}\n"
        "<h2>What this does not do</h2>\n"
        f"{_items(MISSING)}\n"
        '<div class="foot">\n'
        f"<p>{
            esc(
                'The days above are computed from a synthetic invoice carrying one '
                'real transcribed Maersk rate. It is not a client, and no recovery rate '
                'is claimed anywhere on this site.'
            )
        }</p>\n"
        "<p>To run it yourself: <code>quayline serve</code>, then open the address it "
        "prints. It binds to 127.0.0.1 and refuses any other interface, keeps no "
        "account, writes nothing to disk, and logs no request line. To see how far the "
        "rate data reaches, run <code>quayline coverage</code>.</p>\n"
        "</div>\n"
        "</div>"
    )
    return (
        "<!doctype html>\n"
        '<html lang="en">\n'
        "<head>\n"
        '<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        "<title>Quayline: demurrage and detention, recomputed</title>\n"
        f'<meta name="description" content="Recomputes a U.S. ocean demurrage or '
        f"detention invoice one day at a time, from the disclosures the carrier was "
        f'required to publish.">\n'
        f"<style>{stylesheet()}{COMPONENT_CSS}{LANDING_CSS}</style>\n"
        "</head>\n"
        f"<body>\n{body}\n</body>\n"
        "</html>\n"
    )


